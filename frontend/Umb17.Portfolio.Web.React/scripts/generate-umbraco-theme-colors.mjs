import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const projectRoot = process.cwd()
const generatedRoot = path.join(projectRoot, 'src', 'generated')
const themeColorsPath = path.join(generatedRoot, 'umbraco-theme-colors.css')

function readStdin() {
  return new Promise((resolve, reject) => {
    let input = ''

    process.stdin.setEncoding('utf8')
    process.stdin.on('data', (chunk) => {
      input += chunk
    })
    process.stdin.on('end', () => resolve(input))
    process.stdin.on('error', reject)
  })
}

function toThemeColorSlug(value) {
  const slug = String(value)
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

  return slug || 'unnamed'
}

function getThemeColorValue(themeColor, mode) {
  const properties = themeColor.properties ?? {}
  return themeColor[mode] || properties[mode] || null
}

function getThemeColors(payload) {
  if (Array.isArray(payload)) {
    return payload
  }

  if (Array.isArray(payload.themeColors)) {
    return payload.themeColors
  }

  if (Array.isArray(payload.items)) {
    return payload.items
  }

  return []
}

function renderThemeColorCss(themeColors) {
  const tokens = themeColors
    .map((themeColor) => {
      const slug = toThemeColorSlug(themeColor.name)
      const light = getThemeColorValue(themeColor, 'light')
      const dark = getThemeColorValue(themeColor, 'dark')
      const defaultValue = light || dark
      const darkValue = dark || light

      if (!defaultValue && !darkValue) {
        return null
      }

      return {
        darkValue,
        defaultValue,
        name: themeColor.name,
        slug,
      }
    })
    .filter(Boolean)
    .sort((left, right) => left.slug.localeCompare(right.slug))

  const utilityClasses = tokens.flatMap((token) => [
    `bg-theme-${token.slug}`,
    `border-theme-${token.slug}`,
    `fill-theme-${token.slug}`,
    `stroke-theme-${token.slug}`,
    `text-theme-${token.slug}`,
  ])
  const lightThemeLines = tokens.map((token) => `  --theme-color-${token.slug}: ${token.defaultValue};`)
  const darkThemeLines = tokens.map((token) => `  --theme-color-${token.slug}: ${token.darkValue};`)
  const tailwindThemeLines = tokens.map((token) => `  --color-theme-${token.slug}: var(--theme-color-${token.slug});`)

  return `/* This file is generated by scripts/generate-umbraco-theme-colors.mjs. */
${utilityClasses.length ? `@source inline("${utilityClasses.join(' ')}");` : ''}

[data-theme="light"] {
${lightThemeLines.length ? lightThemeLines.join('\n') : '  --theme-color-placeholder: transparent;'}
}

[data-theme="dark"] {
${darkThemeLines.length ? darkThemeLines.join('\n') : '  --theme-color-placeholder: transparent;'}
}

@theme inline {
${tailwindThemeLines.length ? tailwindThemeLines.join('\n') : '  --color-theme-placeholder: var(--theme-color-placeholder);'}
}
`
}

async function main() {
  const payload = JSON.parse(await readStdin())
  const themeColors = getThemeColors(payload)
  const css = renderThemeColorCss(themeColors)

  await mkdir(generatedRoot, { recursive: true })
  await writeFile(themeColorsPath, css, 'utf8')

  process.stdout.write(
    JSON.stringify({
      files: [themeColorsPath],
      themeColorCount: themeColors.length,
    }),
  )
}

await main()
